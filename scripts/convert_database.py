"""Convert trusted local game templates; never import accounts or payment records."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
EXCLUDE = {'napthe', 'payments', 'posts', 'settings'}
EMPTY = {'account', 'player', 'clan', 'history_transaction', 'giftcode', 'notify', 'shop_ky_gui', 'super_rank'}

def statements(text):
    buf, quote, escape = [], False, False
    for c in re.sub(r'^--[^\n]*|/\*![\s\S]*?\*/;', '', text, flags=re.M):
        buf.append(c)
        if escape:
            escape = False
        elif c == '\\' and quote:
            escape = True
        elif c == "'":
            quote = not quote
        elif c == ';' and not quote:
            yield ''.join(buf).strip()[:-1]
            buf = []

def literal_strings(sql):
    # MySQL backslash escaping -> standard PostgreSQL strings, keeping nested JSON intact.
    out, i = [], 0
    while i < len(sql):
        if sql[i] != "'":
            out.append(sql[i]); i += 1; continue
        i += 1; value = []
        while i < len(sql):
            c = sql[i]; i += 1
            if c == '\\':
                c = sql[i]; i += 1
                value.append({'n':'\n', 'r':'\r', 't':'\t', '0':'', 'Z':''}.get(c, c))
            elif c == "'":
                if i < len(sql) and sql[i] == "'":
                    value.append("'"); i += 1
                else:
                    break
            else:
                value.append(c)
        out.append("'" + ''.join(value).replace("'", "''") + "'")
    return ''.join(out)

def convert(source, target):
    text = source.read_text(encoding='utf-8-sig')
    identity = {(t.lower(), c.lower()) for t,c in re.findall(r'ALTER TABLE `(\w+)`\s+MODIFY `(\w+)` [^;]*AUTO_INCREMENT', text)}
    result = ['-- Generated by scripts/convert_database.py; templates only.', 'SET standard_conforming_strings = on;']
    tables = []
    for sql in statements(text):
        match = re.match(r'CREATE TABLE `(\w+)`\s*\(([\s\S]*)\) ENGINE=', sql)
        if match:
            table, body = match.groups(); table = table.lower()
            if table in EXCLUDE: continue
            columns = []
            for line in body.splitlines():
                col = re.match(r'\s*`(\w+)`\s+(.*?)(?:,)?$', line)
                if not col: continue
                name, decl = col.groups(); name = name.lower()
                decl = re.sub(r'\b(?:CHARACTER SET|COLLATE)\s+\w+', '', decl, flags=re.I)
                decl = re.sub(r'\b(?:tinyint|smallint|mediumint|int)\(\d+\)', 'INTEGER', decl, flags=re.I)
                decl = re.sub(r'\bbigint\(\d+\)', 'BIGINT', decl, flags=re.I)
                decl = re.sub(r'\b(?:longtext|mediumtext)\b', 'TEXT', decl, flags=re.I)
                # The dump contains strings exceeding declared MySQL VARCHAR lengths.
                # PostgreSQL rejects those rather than silently truncating them.
                decl = re.sub(r'\bvarchar\(\d+\)', 'TEXT', decl, flags=re.I)
                decl = re.sub(r'\bdouble\b', 'DOUBLE PRECISION', decl, flags=re.I)
                decl = re.sub(r'current_timestamp\(\)', 'CURRENT_TIMESTAMP', decl, flags=re.I)
                decl = re.sub(r'\s+ON UPDATE CURRENT_TIMESTAMP', '', decl, flags=re.I)
                decl = decl.replace(' unsigned', '')
                if (table, name) in identity:
                    decl = re.sub(r'\bNOT NULL\b', 'GENERATED BY DEFAULT AS IDENTITY', decl)
                if decl.upper().startswith('TEXT'):
                    decl = re.sub(r'DEFAULT (\d+)', r"DEFAULT '\1'", decl)
                if table == 'account' and name in {'email','token','xsrf_token','newpass'}:
                    decl += " DEFAULT ''"
                columns.append(f'{name} {decl.strip()}')
            result.append(f'CREATE TABLE {table} (' + ', '.join(columns) + ');')
            tables.append(table)
            continue
        match = re.match(r'INSERT INTO `(\w+)`', sql)
        if match:
            table = match[1].lower()
            if table in EXCLUDE | EMPTY: continue
            sql = literal_strings(sql)
            sql = re.sub(r'`(\w+)`', lambda m:m[1].lower(), sql)
            result.append(sql + ';')
            continue
        match = re.match(r'ALTER TABLE `(\w+)`([\s\S]*)', sql)
        if match and match[1].lower() not in EXCLUDE:
            table, body = match[1].lower(), match[2]
            pk = re.search(r'ADD PRIMARY KEY \(([^)]+)\)', body)
            if pk:
                cols = pk[1].replace('`','').lower()
                result.append(f'ALTER TABLE {table} ADD PRIMARY KEY ({cols});')
            for name,cols in re.findall(r'ADD UNIQUE KEY `(\w+)` \(([^)]+)\)', body):
                cols = cols.replace('`','').lower()
                result.append(f'CREATE UNIQUE INDEX {table}_{name.lower()}_uq ON {table} ({cols});')
    result += [
        'CREATE UNIQUE INDEX player_name_uq ON player (lower(name));',
        'ALTER TABLE player ADD CONSTRAINT player_account_fk FOREIGN KEY (account_id) REFERENCES account(id);',
        "UPDATE achievement_template SET info1='Cùng khám phá', info2='Tiếp tục hành trình cùng bạn bè', max_count=2147483647 WHERE id=11;",
        "UPDATE task_badges_template SET name='Cùng luyện tập', maxcount=2147483647 WHERE id=1;",
    ]
    for table, column in sorted(identity):
        if table not in EXCLUDE:
            result.append(f"SELECT setval(pg_get_serial_sequence('{table}', '{column}'), GREATEST(COALESCE((SELECT MAX({column}) FROM {table}), 0) + 1, 1), false);")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(result) + '\n', encoding='utf-8')
    print(f'Converted {len(tables)} tables; excluded {sorted(EXCLUDE)}; no imported accounts.')

if __name__ == '__main__':
    convert(ROOT / 'b.sql', ROOT / 'db' / 'V1__game.sql')
